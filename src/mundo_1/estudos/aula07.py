# Aula 007: Operadores aritméticos.

# Há diversos tipos de operações aritméticas que dá pra fazer em Python, além da adição etc..

# Lista de operações como exemplo:

print(5+2) # Adição

print(5-2) # Subtração

print(5*2) # Multiplicação

print(5/2) # Divisão

print(5//2) # Divisão inteira (se o resultado fosse ter vírgula na divisão, ele para  por aí.)

print(5%2) # Resto da divisão (O resto que sobra numa divisão inteira é o que aparecerá aqui.)

print(5**2) # Potenciação (nesse caso é 5 ao quadrado (2))

print(25**(1/2)) # Nesse caso, o 25 elevado a 1/2 (meio) será a sua raiz quadrada.
