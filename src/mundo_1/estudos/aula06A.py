# Com o input do usuário digitando o número 1 e o número 2 das variáveis que vão ser armazenadas, converte em números inteiros com int()
n1 = int(input('Digite o primeiro número: ')) 
n2 = int(input('Digite o segundo número: '))

# Variável que soma o primeiro valor com o segundo
resultado = n1 + n2

# Print sendo chamado para exibir o resultado da soma.
print(f'O resultado da soma entre {n1} e {n2} é: {resultado}')
