# Desafio 006: Crie um algoritmo que leia um número e mostre o dobro, triplo e sua raiz quadrada.
n = int(input('Digite um número: ')) # Armazenará o número digitado na variável n

print(f'O número escolhido foi: {n}') # Mostra o número escolhido.

# Mostra o dobro do número, o seu triplo e sua raiz quadrada com os operadores aritméticos.
print(f'\nO dobro dele é {n*2}, o seu triplo é {n*3}, e sua raiz quadrada é {n**(1/2)}.\n')

