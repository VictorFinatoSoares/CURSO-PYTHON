#Desafio 005: Faça um programa que leia um número e mostre o seu sucessor e antecessor.
n = int(input('Digite um Número: ')) # Guardará o número digitado pelo usuário na variável n.

# Mostra com uma mensagem o número escolhido, o antecessor e seu sucessor, respectivamente.
print(f'O número {n} tem como antecessor o número {n-1} e sucessor o número {n+1}.')
